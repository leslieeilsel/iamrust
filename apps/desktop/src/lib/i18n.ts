export function translate(language: Language, source: string): string {
  if (language === 'zh-CN') return source;
  const exact = enUS[source];
  if (exact !== undefined) return exact;
  for (const [pattern, replacement] of enPatterns) {
    if (pattern.test(source)) return source.replace(pattern, replacement);
  }
  return source;
}

export function tr(source: string): string {
  return translate(currentLanguage(), source);
}

export function currentLanguage(): Language {
  return useChatStore.getState().settings.language;
}

export function hasEnglishTranslation(source: string): boolean {
  if (enUS[source] !== undefined) return true;
  return enPatterns.some(([pattern]) => pattern.test(source));
}
